#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
train_tokenizer.py — 由 dsh-llm-architect (llm_data_forge) 生成。
用途：用 tokenizers 库在云端节点训练 BPE/Unigram/WordPiece 分词器。
依赖：pip install tokenizers
输入：jsonl 语料（取 "text" 字段），输出 tokenizer.json + vocab.json + merges.txt。

用法：
    python train_tokenizer.py --corpus clean.jsonl --output-dir ./tokenizer_output
"""

import argparse
import json
import os
import sys


def parse_args():
    p = argparse.ArgumentParser(description="Tokenizer trainer (generated by dsh-llm-architect)")
    p.add_argument("--corpus", default="{{CORPUS_PATH}}", help="jsonl 语料路径")
    p.add_argument("--output-dir", default="{{OUTPUT_DIR}}")
    p.add_argument("--model", default="{{MODEL_TYPE}}", choices=["bpe", "unigram", "wordpiece"])
    p.add_argument("--vocab-size", type=int, default={{VOCAB_SIZE}})
    p.add_argument("--character-coverage", type=float, default={{CHARACTER_COVERAGE}})
    p.add_argument("--special-tokens", default=None, help="JSON 列表字符串，默认读取配置")
    return p.parse_args()


def iter_texts(path):
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                rec = json.loads(line)
            except json.JSONDecodeError:
                continue
            text = rec.get("text") if isinstance(rec, dict) else None
            if isinstance(text, str) and text:
                yield text


def main():
    args = parse_args()
    try:
        from tokenizers import Tokenizer, models, trainers, pre_tokenizers, decoders
        from tokenizers.models import BPE, Unigram, WordPiece
    except ImportError:
        print("[fatal] 请先安装: pip install tokenizers", file=sys.stderr)
        return 2

    os.makedirs(args.output_dir, exist_ok=True)
    special = args.special_tokens or {{SPECIAL_TOKENS_PY}}

    if args.model == "bpe":
        model = BPE(unk_token="<unk>")
        trainer = trainers.BpeTrainer(
            vocab_size=args.vocab_size,
            special_tokens=special,
            min_frequency=2,
            show_progress=True,
            initial_alphabet=pre_tokenizers.ByteLevel.alphabet(),
        )
        tokenizer = Tokenizer(model)
        tokenizer.pre_tokenizer = pre_tokenizers.ByteLevel(add_prefix_space=False)
        tokenizer.decoder = decoders.ByteLevel()
    elif args.model == "unigram":
        model = Unigram()
        trainer = trainers.UnigramTrainer(
            vocab_size=args.vocab_size,
            special_tokens=special,
            unk_token="<unk>",
            show_progress=True,
        )
        tokenizer = Tokenizer(model)
        tokenizer.pre_tokenizer = pre_tokenizers.Metaspace()
        tokenizer.decoder = decoders.Metaspace()
    else:
        model = WordPiece(unk_token="<unk>")
        trainer = trainers.WordPieceTrainer(
            vocab_size=args.vocab_size,
            special_tokens=special,
            show_progress=True,
        )
        tokenizer = Tokenizer(model)
        tokenizer.pre_tokenizer = pre_tokenizers.WhitespaceSplit()
        if hasattr(decoders, "WordPiece"):
            tokenizer.decoder = decoders.WordPiece()

    print(f"[info] training {args.model} tokenizer, vocab_size={args.vocab_size}, corpus={args.corpus}")
    tokenizer.train_from_iterator(iter_texts(args.corpus), trainer=trainer, length=None)

    tokenizer.save(os.path.join(args.output_dir, "tokenizer.json"))
    # 兼容 transformers 的词表导出
    vocab = tokenizer.get_vocab()
    with open(os.path.join(args.output_dir, "vocab.json"), "w", encoding="utf-8") as f:
        json.dump(vocab, f, ensure_ascii=False)
    print(f"[done] vocab size = {len(vocab)} -> {args.output_dir}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
