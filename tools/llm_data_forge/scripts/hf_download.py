#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
hf_download.py — 由 dsh-llm-architect (llm_data_forge) 生成的数据集下载脚本。

用途：从 HuggingFace Hub 下载开源数据集（如 wikimedia/wikipedia）到本地/云端目录。
运行环境：任意装了 Python3 的机器（建议云端节点，Wikipedia 全量约数十 GB）。
依赖：pip install datasets huggingface_hub

用法：
    export HF_TOKEN=hf_xxx            # 私有/受限数据集需要；公开数据集可省略
    python hf_download.py
"""

import argparse
import os
import sys


def parse_args():
    p = argparse.ArgumentParser(description="HuggingFace dataset downloader (generated by dsh-llm-architect)")
    p.add_argument("--dataset-id", default="{{DATASET_ID}}", help="数据集 ID，如 wikimedia/wikipedia")
    p.add_argument("--config", default="{{CONFIG_NAME}}", help="数据集配置名（如语言代码 zh / 20231101.zh）")
    p.add_argument("--split", default="{{SPLIT}}", help="切分名：train / validation / test")
    p.add_argument("--limit-docs", type=int, default={{LIMIT_DOCS}}, help="只取前 N 条（0 表示全量）")
    p.add_argument("--out-dir", default="{{OUT_DIR}}", help="输出目录")
    p.add_argument("--field", default=None, help="提取的字段（默认自动探测 text/content）")
    return p.parse_args()


def main():
    args = parse_args()
    token = os.environ.get("HF_TOKEN") or os.environ.get("HUGGING_FACE_HUB_TOKEN")
    if not token:
        print("[warn] 未设置 HF_TOKEN 环境变量（公开数据集可忽略）", file=sys.stderr)

    os.makedirs(args.out_dir, exist_ok=True)

    try:
        from datasets import load_dataset
    except ImportError:
        print("[fatal] 请先安装依赖: pip install datasets huggingface_hub", file=sys.stderr)
        return 2

    print(f"[info] loading {args.dataset_id} / {args.config} / {args.split} ...")
    ds = load_dataset(args.dataset_id, args.config, split=args.split)
    print(f"[info] {len(ds)} docs in split")

    field = args.field
    if not field:
        for cand in ("text", "content", "body"):
            if cand in ds.column_names:
                field = cand
                break
    if not field:
        print(f"[fatal] 无法定位文本字段，列: {ds.column_names}", file=sys.stderr)
        return 3
    print(f"[info] using field: {field}")

    out_path = os.path.join(args.out_dir, f"{os.path.basename(args.dataset_id.replace('/', '_'))}.jsonl")
    n = 0
    total_bytes = 0
    with open(out_path, "w", encoding="utf-8") as f:
        for rec in ds:
            text = rec.get(field)
            if not isinstance(text, str) or not text.strip():
                continue
            meta = {k: v for k, v in rec.items() if k != field}
            f.write(__import__("json").dumps({"text": text, "meta": meta}, ensure_ascii=False) + "\n")
            n += 1
            total_bytes += len(text.encode("utf-8"))
            if args.limit_docs and n >= args.limit_docs:
                break
            if n % 50000 == 0:
                print(f"[info] {n} docs, {total_bytes / 1e9:.2f} GB ...")

    print(f"[done] {n} docs ({total_bytes / 1e9:.2f} GB) -> {out_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
